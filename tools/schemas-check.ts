// Validates serialized fixture documents against schemas/page-export.schema.json.
import { readdirSync, readFileSync } from "node:fs";
import { toJsonl } from "../src/serialize/jsonl.ts";
import { fixtures } from "../tests/fixtures/documents.ts";
import { buildExamples } from "./examples.ts";
import { validateJsonl } from "./schema-validator.ts";

let failed = false;
const report = (name: string, errors: string[]) => {
  if (errors.length) {
    failed = true;
    console.error(`schemas:check FAIL ${name}\n  ${errors.join("\n  ")}`);
  } else {
    console.log(`schemas:check ok ${name}`);
  }
};

for (const [name, doc] of Object.entries(fixtures))
  report(`fixture ${name}`, validateJsonl(toJsonl(doc)));

const root = new URL("../", import.meta.url);
const expected = buildExamples();
const read = (path: string): string | null => {
  try {
    return readFileSync(new URL(path, root), "utf8");
  } catch {
    return null;
  }
};
let files: string[] = [];
try {
  files = readdirSync(new URL("examples/", root));
} catch {
  report("examples/", ["directory missing; run `bun run examples`"]);
}
const onDisk = files
  .filter((f) => !f.startsWith("."))
  .map((f) => `examples/${f}`);
for (const path of onDisk) {
  if (path.endsWith(".jsonl"))
    report(`${path} schema`, validateJsonl(read(path) ?? ""));
  if (!(path in expected))
    report(`${path} fresh`, ["not generated by tools/examples.ts"]);
}
for (const [path, content] of Object.entries(expected))
  report(
    `${path} fresh`,
    read(path) === content ? [] : ["stale or missing; run `bun run examples`"],
  );

process.exit(failed ? 1 : 0);
